def result_for(rule, letter, cov, vs, m, fingerprint, phase=None, identities=None):
    """One rule on one board. Everything that is not a positive, current PASS is INCONCLUSIVE or FAIL."""
    rid = rule["id"]; c = cov.get(rid) or {}
    if phase and rule["verification_phase"] not in _phases_up_to(phase):
        return dict(result=NOT_APPLICABLE, why="verified at %s, later than the phase being reported" % rule["verification_phase"], evidence=None)
    w = (c.get("waiver") or {})
    if w.get("active"):
        return dict(result=WAIVED, why="waived by %s until %s: %s" % (w.get("authority"), w.get("expiry"), w.get("reason", "")), evidence=w.get("evidence"))
    if c.get("maturity") in ("OPEN", "DOCUMENTED_ONLY"):
        return dict(result=INCONCLUSIVE, why="no verification: %s" % c.get("note", "")[:160], evidence=None)
    if c.get("maturity") == "SOURCE_UNVERIFIED":
        return dict(result=INCONCLUSIVE, why="the authority behind this rule's limit is not established: %s" % c.get("note", "")[:140], evidence=None)
    if c.get("maturity") == "OWNER_DECISION_REQUIRED":
        return dict(result=INCONCLUSIVE, why="an owner decision is open: %s" % c.get("note", "")[:140], evidence=None)
    if c.get("maturity") == "VERIFIED_MANUALLY":
        doc = (c.get("verification") or {}).get("document")
        if not doc:
            return dict(result=INCONCLUSIVE, why="a manual verification with no record is not evidence", evidence=None)
        ok, why = _document_current(doc, c.get("verified_sha"))
        if ok:
            # AND BOUND TO WHAT IT READ ON THE BOARD (26 September 2026): a desk review of a circuit names the nets it
            # read, and it stops counting the moment those nets change on the board's current netlist.
            nok, nwhy = verified_nets_current(c, letter, m)
            if not nok: return dict(result=INCONCLUSIVE, why=nwhy, evidence=doc)
            if nwhy: why = "%s, %s" % (why, nwhy)
        return (dict(result=PASS, why=why, evidence=doc) if ok
                else dict(result=INCONCLUSIVE, why=why, evidence=doc))
    if c.get("maturity") == "GENERATED_ONLY":
        return dict(result=INCONCLUSIVE, why="generation intends to comply and nothing verifies it: %s" % c.get("note", "")[:140], evidence=None)
    names = _names(c, letter)
    if not names:
        return dict(result=INCONCLUSIVE, why="the coverage map names no verdict for an enforced rule", evidence=None)
    # A RULE MAY BE VERIFIED BY MORE THAN ONE TOOL, and several are: a placement is judged both by the DRC on
    # the placed board and by the escape-fan predictor, and a part is judged both by the code the BOM carries
    # and by asking the fabricator whether that code is the part. Where a rule names several, the WORST result
    # decides, because a rule is satisfied only when every tool that verifies it says so.
    # `names` above: _names, which reads a board's own readings where the row names them (verdict_by_board).
    if rule["verification_phase"] == "ROUTED_BOARD" and ROUTE_GATE not in names:
        n_un, why_un = _unrouted(vs, m, fingerprint, identities)
        if n_un: return dict(result=INCONCLUSIVE, why=why_un, evidence=(vs.get(ROUTE_GATE) or {}).get("_path"))
    worst = None
    for name in names:
        rec = vs.get(name)
        if rec is None:
            r = dict(result=INCONCLUSIVE, why="no %s verdict for this board" % name, evidence=None)
        else:
            ok, why = _fresh(rec, m, fingerprint, identities, rule)
            if ok:
                ok, why = _after_meaning_changed(rec, name, c, letter)
            if not ok:
                r = dict(result=INCONCLUSIVE, why=why, evidence=rec.get("_path"))
            elif rec.get("applicable") is False:
                # THE GATE SAYING THE QUESTION CANNOT ARISE HERE IS AN ANSWER, AND NOTHING READ IT (17 September
                # 2026). `clock_check` writes "this board carries no crystal, so CLK-001 has nothing on it to
                # judge" with applicable false, and it was written on 16 September precisely so that a reader
                # could tell "not applicable" from "could not judge"; this reader never looked at the field, so
                # board A's CLK-001 counted as an unanswered question about a crystal it does not have. The
                # registry's condition says a rule COULD apply to a board; a current verdict from the tool that
                # looked says whether the thing it is about is there. The pair leaves the denominator, which is
                # what NOT_APPLICABLE means everywhere else in this file, and the note travels with it.
                r = dict(result=NOT_APPLICABLE, why=(rec.get("note") or "the gate reports that this rule does "
                                                     "not apply to this board"), evidence=rec.get("_path"))
            else:
                res = rec.get("result") or rec.get("verdict")
                # AN ADVISORY VERDICT IS A MEASUREMENT AND NOT A BAR (16 September 2026). The verdict channel
                # has carried the flag since 15 September and this reader did not look at it, so a tool whose
                # own author had marked it "not a bar" would still have failed its rule on every board. A
                # measurement counts as no verification at all here, which is the honest reading: the rule is
                # unverified until something decides it.
                if rec.get("advisory"):
                    r = dict(result=INCONCLUSIVE, why="%s is advisory: a measurement for the record, not a bar (%s)"
                             % (name, str(rec.get("counts"))[:90]), evidence=rec.get("_path"))
                elif res == "PASS": r = dict(result=PASS, why="%s PASS of %s" % (name, rec.get("denominator")), evidence=rec.get("_path"))
                elif res == "FAIL": r = dict(result=FAIL, why="%s FAIL: %s" % (name, str(rec.get("counts"))[:120]), evidence=rec.get("_path"))
                else:
                    # AN INCONCLUSIVE READING EXPLAINS ITSELF AND THIS READER THREW THE EXPLANATION AWAY (19
                    # September 2026). Every gate writes a note saying WHY it could not judge, and thirteen
                    # rule-board pairs on the readiness pages read "assembly_set INCONCLUSIVE", which is the
                    # tool's name and its verdict and not one word about the cause; the sentence "no
                    # single-ended controlled line was found to judge, and this board does not declare that it
                    # has none" was sitting in the verdict file the whole time. A gate that names what it hit
                    # is a law here (16 September) and a reader that drops the name breaks it just as surely.
                    note = " ".join(str(rec.get("note") or "").split())
                    mi = " ".join(str(rec.get("missing_input") or "").split())
                    tail = (": " + (mi or note)[:160]) if (mi or note) else ""
                    r = dict(result=INCONCLUSIVE, why="%s %s%s" % (name, res, tail), evidence=rec.get("_path"))
        order = {FAIL: 0, INCONCLUSIVE: 1, PASS: 2}
        if worst is None or order[r["result"]] < order[worst["result"]]: worst = r
    return worst


def _after_meaning_changed(rec, name, c, letter):
    """(ok, why): was this verdict taken after its tool last changed what the verdict MEANS for this rule?

    26 September 2026 (MESHSAT-1357). A rule's digest moves when the RULE's demands change and a verdict's epoch
    when the audit restarts; neither moves when the TOOL is corrected to measure what the rule always demanded.
    jlc_certify was: until that day CERTIFIED did not establish that the part was the one the row or its land
    names (the tracked per-board verdicts of boards C and P read PASS over C2089, a TO-92-3 part, certified as sixteen panel
    LEDs and XSD's C4661 on the Keystone 3568 fuse-holder land). A coverage row names, per verdict, the instant
    its tool's meaning changed (`evidence_not_before`, `<letter>` expanded), and a reading taken before it is not
    current evidence for that rule until it is re-taken. A floor that cannot be read is not a floor: it refuses."""
    floors = c.get("evidence_not_before") or {}
    if not isinstance(floors, dict):
        return False, "the coverage map's evidence_not_before is not a map of verdict to instant (%r)" % (str(floors)[:40],)
    for pat, since in floors.items():
        if str(pat).replace("<letter>", letter) != name:
            continue
        e = _instant(str(since))
        if e is None:
            return False, "the coverage map's evidence_not_before for %s cannot be read (%r)" % (name, str(since)[:30])
        t = _instant(str(rec.get("ts", "")))
        if t is None or t < e:
            return False, ("%s was taken %s, before %s, when its tool changed what the verdict means; re-take it"
                           % (name, str(rec.get("ts") or "at no stated time")[:19], str(since)[:25]))
    return True, "current"



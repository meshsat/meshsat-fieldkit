"""Compute each board's result for every rule that applies to it, and the readiness state of the set
(MESHSAT-862, 16 September 2026; owner instruction of 16 September 00:30).

Every applicable rule-board pair gets exactly one of PASS, FAIL, INCONCLUSIVE, WAIVED, NOT_APPLICABLE, and
the rule that makes this worth reading is: **absence is never a pass**. A missing verdict file, a verdict
older than the evidence epoch, a verdict taken under a different rule-set fingerprint or a different board,
a rule with no implementation, a rule whose authority is unverified, a rule whose owner decision is open:
each of those is INCONCLUSIVE, and an INCONCLUSIVE blocker keeps the set out of READY_FOR_PROTOTYPE.

Where a result comes from:
  * the registry says whether the rule applies to this board (rules_lib.rules_for);
  * the coverage map says which tool verifies it and which verdict file carries the evidence;
  * the verdict file, if it exists in the board's project `out/` or its `routed/` snapshot, carries the
    result, the denominator and its own inputs;
  * the readiness manifest says what evidence is current (the epoch) and whether promotion is frozen.

Percentages: four numbers over ONE denominator (the applicable rule-board pairs required at the phase being
reported), summing to 100 subject to rounding. The gate state is printed BEFORE them, and the WITH_WAIVERS
qualifier cannot be hidden by any of them. The project aggregate sums rule-board pairs; it never averages
board percentages.

Those percentages are a HISTORICAL AGGREGATE OF MIXED REVISIONS and are printed under that name (review of 26
September 2026). Every row also carries an EVIDENCE CLASS (CURRENT_CANDIDATE, VALID_HISTORICAL, AWAITING_REVALIDATION,
DESK_REVIEW, PHYSICAL_TEST or NO_EVIDENCE; see `evidence_class`), which binds a reading to the board's current netlist,
board file, layout and tool, and `rules_render.py` renders v2/docs/CURRENT-EVIDENCE.md from it.

The TOOL a reading is judged against is its CODE BUNDLE since 26 September 2026 (the review of the 22:35 progress
report, finding D2): the entry script and every local module it imports, each by content hash, recorded by verdict.py;
an older reading is judged by its writer's hash and its imports' commit dates (`_tool_detail`). Each row also carries the
class the entry-script instrument of 20 September would give (`writer_only_class`), so the page can say which rows
changed class because of the bundle.

LAYOUT ENTRY is staged since the same day (finding A): `layout_entry` counts only the holds and feasibility stages that
gate layout entry, plus every `layout_entry_requires` of a hold staged at fabrication release or prototype
verification, and lists the rest separately. The result is written into each board's audit as `layout_entry`.

Usage:
  rules_status.py [--board <letter>] [--phase <SCHEMATIC|PLACED_BOARD|ROUTED_BOARD|RELEASE_PACKAGE>]
                  [--out-dir out/rule-audit] [--json]

The per-board markdown is generated by rules_render.py from the JSON this writes; this tool computes and
never formats a document.
"""

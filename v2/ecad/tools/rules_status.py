def _explicit_out(argv):
    """The directory the caller named, or None. A set-level verdict belongs beside the set's own gates; a run
    told to write elsewhere is a run that must leave the tree exactly as it found it."""
    return _v.opt(argv, "--out-dir", None)


def _finish(argv, all_rows, per_board, m, fp, phase, out_dir):
    """The run's own summary and its readiness verdict. Split out of `main` so that a scoped run reaches
    exactly this and nothing else: the set-level completeness verdict above it is written only by a run that
    saw the whole set."""
    agg = counts(all_rows); state = gate_state(all_rows, m)
    summary = dict(manifest_version=m.get("manifest_version"), rule_set_fingerprint=fp,
                   promotion_frozen=bool(m.get("promotion", {}).get("frozen")), phase=phase or "ALL",
                   gate_state=state, counts=agg, boards={k: counts(v["rows"]) for k, v in per_board.items()},
                   evidence=evidence_counts(all_rows),
                   evidence_boards={k: evidence_counts(v["rows"]) for k, v in per_board.items()},
                   refused_as_invalidated=sorted(_REFUSED), register_errors=registers()["errors"])
    json.dump(summary, open(os.path.join(out_dir, "summary.json"), "w"), indent=1)
    print("\nreadiness: %s   (manifest %s, rule set %s%s)" % (state, m.get("manifest_version"), fp,
          ", promotion frozen" if m.get("promotion", {}).get("frozen") else ""))
    # THE PERCENTAGE IS A HISTORICAL AGGREGATE OF MIXED REVISIONS (26 September 2026, the review of that day): it sums
    # readings of layouts that predate the corrected netlists and readings under tools that have changed since. It is
    # printed under that name and never as readiness; the evidence line under it is the current-candidate count.
    print("historical aggregate, mixed revisions: PASS %.1f%%  waived %.1f%%  failed %.1f%%  inconclusive %.1f%%  of %d "
          "applicable required rule-board pair(s)"
          % (agg["pass_percent"], agg["waived_percent"], agg["fail_percent"], agg["inconclusive_percent"], agg["denominator"]))
    ev = summary["evidence"]
    print("evidence: %d PASS on the current candidate; %s" % (ev["current_pass"], "  ".join(
        "%s %d" % (k, ev[k]) for k in EVIDENCE_CLASSES)))
    if _REFUSED:
        print("evidence: %d reading(s) refused as invalidated by content (v2/docs/evidence/INVALIDATED-*.md): %s"
              % (len(_REFUSED), ", ".join(sorted(_REFUSED))[:300]))
    if registers()["errors"]:
        print("evidence: THE EVIDENCE REGISTERS CANNOT BE READ, so no reading counts as current: %s" % "; ".join(registers()["errors"]))
    if _DISPLACED:
        # A reading that declares it lacked its input stood in front of one that had it, because its rule-set
        # fingerprint is current and the other's is not. It is legal by the order in `_supersedes` and it is
        # exactly how a page can change under the reader with nothing on it to show why (19 September 2026).
        seen = []
        for _n, _mi, _ofp in _DISPLACED:
            if (_n, _mi, _ofp) in seen: continue
            seen.append((_n, _mi, _ofp))
        print("\nNOTE: %d reading(s) that declare a MISSING INPUT stand in front of a measured one, because the "
              "measured one was taken under a superseded version of the rule it decides (asked rule by rule "
              "where the verdict carries its digests, and by the set fingerprint where it does not). Re-take "
              "those on the board, where the tool has its input (retake_gate.sh), rather than reading the "
              "page as an answer:" % len(seen))
        for _n, _mi, _ofp in seen[:8]:
            print("  %-22s displaces a reading taken under %s; it lacked: %s" % (_n, _ofp or "(no fingerprint)", _mi or "(unsaid)"))
    if "--json" in argv: print(json.dumps(summary, indent=1, sort_keys=True))
    res = _v.PASS if state.startswith("READY") else (_v.FAIL if state.startswith("NOT_READY") else _v.INCONCLUSIVE)
    return _v.write("rules_status", res, counts=agg, denominator=agg["denominator"],
                    evidence=["%s %s %s" % (r["rule"], r["result"], r["why"][:80]) for r in all_rows if r["result"] in (FAIL, INCONCLUSIVE)][:40],
                    inputs={"manifest_version": m.get("manifest_version"), "rule_set_fingerprint": fp},
                    note="gate state %s; %s" % (state, "promotion frozen" if m.get("promotion", {}).get("frozen") else "promotion open"),
                    out_dir=out_dir)



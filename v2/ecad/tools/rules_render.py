def entry_blockers(st, holds):
    """[{rule, result, now, retake, kind, closes, owner}] for one board: every applicable required schematic-phase
    rule that is not a PASS on evidence layout entry accepts, and the board's hold. See the block comment above."""
    L = st["board"]
    owner = {k: (o % L.upper()) if "%s" in o else o for k, _t, o in ENTRY_KINDS}
    art = "netlist" if (st.get("candidate") or {}).get("netlist_sha16") else "board file"
    out = []
    for r in _required(st["rows"]):
        if r["verification_phase"] != "SCHEMATIC": continue
        if r["result"] == S.PASS and _entry_class_ok(r): continue
        w = ", ".join(r.get("retake_blockers") or r.get("writers") or []) or "its tool"
        rc, cause, res = r.get("retake_class"), r.get("retake_cause"), r["result"]
        tail = "" if res == S.PASS else "; today's reading is %s, which the re-take may repeat" % res
        if rc is None:
            kind, closes = "OTHER", "this audit carries no re-take projection (it predates them): run rules_status.py"
        elif _entry_class_ok(r, "retake_class"):
            if _entry_class_ok(r):
                kind, closes = "DESIGN", "the reading is current and reads %s" % res
            else:
                kind, closes = "RETAKE", "%s re-taken on the committed %s%s" % (w, art, tail)
        elif rc == S.NO_EVIDENCE:
            kind, closes = "REGISTRY", "the coverage map gives it no deciding verification (%s)" % cause
        elif cause in ("UNBOUND", "PREDATES_ARTEFACT"):
            notes = "; ".join(TOOL_NOTES[x] for x in (r.get("retake_blockers") or []) if x in TOOL_NOTES)
            kind, closes = "TOOL", "%s taught to record by sha the %s that ties its reading to this board%s, then re-taken%s" % (
                w, art, (" (%s)" % notes) if notes else "", tail)
        elif cause == "LAYOUT_NOT_CURRENT":
            kind, closes = "LAYOUT_TOOL", ("%s reads only the board file, so its reading can be current only on a layout "
                                           "that carries the netlist; taught to judge %s, then re-taken%s"
                                           % (w, NETLIST_FORM.get(r["rule"], "the netlist"), tail))
        elif cause == "CONFIG_UNDECLARED":
            kind, closes = "CONFIG", "%s audited into rules_status.CONFIG_INPUTS, then re-taken%s" % (w, tail)
        elif cause == "CONFIG_CHANGED":
            kind, closes = "OTHER", "a configuration input %s reads is not committed here: committed, then re-taken%s" % (w, tail)
        elif cause == "OTHER_BOARD":
            kind, closes = "OTHER", "every board it reads made current, then re-taken%s" % tail
        else:
            kind, closes = "OTHER", "re-taken, after %s%s" % (cause, tail)
        out.append(dict(rule=r["rule"], short=r.get("short_name", ""), result=res,
                        now="%s (%s)" % (r["evidence_class"], r["evidence_cause"]),
                        retake="%s (%s)" % (rc, cause) if rc else "not computed", kind=kind, closes=closes,
                        owner=owner[kind], writers=list(r.get("writers") or [])))

    i, j = A.span(t, "S-119")
    blk = t[i:j]
    tm = re.search(r"(?m)^    title: >-\n", blk)
    if not tm:
        refuse("S-119's title is not a folded block")
    s119_title = blk[tm.end():].rstrip("\n")
    out = t[:i] + t[j:]
    # 2. the new item after the last open item (before closed_items)
    k = out.index("\nclosed_items:\n")
    out = out[:k + 1] + "  - id: %s\n    class: SESSION\n    status: OPEN\n    title: >-\n%s" % (new_id, A.fold(title, 6, 120)) + out[k + 1:]

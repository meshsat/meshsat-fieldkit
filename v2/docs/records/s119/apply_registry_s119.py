             "(v2/docs/records/s119/reconcile_s119.out section 3). The 400 kHz row (way (b): U3's inductor, IADPT resistor, "
             "compensation and FET pair, a 10 mOhm input sense and IIN_HOST at most 6.35 A; the model's largest U3B input is "

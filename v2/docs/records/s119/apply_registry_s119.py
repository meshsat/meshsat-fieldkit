    print("apply_registry_s119 close: S-119 closed by commit %s; %s opened (U3B's drafted FETs); REQ-072 waits on %s and "
          "gained one evidence entry, its result FAIL" % (commit[:8], new_id, ", ".join(a72["waits_on"])))

def freeze(data):
    z = os.path.join(ROOT, data["h3"]["zip"])
    raw = zipfile.ZipFile(z).read(data["h3"]["member"])
    h3 = yaml.safe_load(raw)
    out = {"source": "%s!%s" % (data["h3"]["zip"], data["h3"]["member"]), "member_sha256": hashlib.sha256(raw).hexdigest(),
           "baseline_state": h3.get("baseline_state"), "needs_document_sha256": h3.get("needs_document_sha256"),
           "owner_rulings": [x["id"] for x in h3["owner_rulings"]],
           "session_choices": [x["id"] for x in h3["session_choices"]],
           "open_items": [x["id"] for x in h3["open_items"]], "closed_items": [x["id"] for x in h3["closed_items"]],
           "records": {r["id"]: {k: r.get(k) for k in DIGEST_FIELDS} for r in h3["records"]},
           "evidence_counts": {r["id"]: len(r.get("evidence") or []) for r in h3["records"]}}
    return json.dumps(out, indent=1, sort_keys=True, ensure_ascii=False) + "\n"



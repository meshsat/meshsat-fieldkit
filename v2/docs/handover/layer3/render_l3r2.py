def spec_record(r, byid, rulings, choices, lay, tp, pend, changed, dec, data):
    rid = r["id"]
    sb = r.get("satisfied_by") or {}
    src = []
    for x in r.get("rulings") or []: src.append("%s (owner, %s)" % (x, rulings[x]["ruled_on"]) if x in rulings else x)
    for x in r.get("choices") or []: src.append("%s (session, %s)" % (x, choices[x]["taken_on"]) if x in choices else x)
    files = [s for s in (r.get("source") or []) if not str(s).startswith(("owner ruling", "session choice"))]
    appl = "%s (%s%s)" % (r.get("prototype_1") or "n/a", r.get("prototype_1_basis") or "",
                          (": " + p(r.get("prototype_1_why"))) if r.get("prototype_1_why") else "")
    ver = "%s at %s" % (", ".join(r.get("verification_method") or []), r.get("verification_phase"))
    if r.get("final_phase") and r.get("final_phase") != r.get("verification_phase"): ver += ", final %s" % r["final_phase"]
    reading = "%s%s%s" % (r.get("evidence_result"), (" at " + r["evidence_phase"]) if r.get("evidence_phase") else "",
                          (", " + r["evidence_class"]) if r.get("evidence_class") else "")
    waits = ["%s (layer %s)" % (w, (lay.get(w) or {}).get("layer", "?")) for w in (r.get("waits_on") or [])]
    L = ["#### %s (%s, %s, %s)" % (rid, r["kind"], r.get("status"), r.get("release_effect")), "",
         "- **Statement:** " + p(r["statement"]),
         "- **Applicability:** " + appl,
         "- **Acceptance:** " + p(r["acceptance"]),
         "- **Verification:** " + ver + "; allocated to " + ", ".join(r.get("allocated_to") or []),
         "- **Sources:** need %s; %s%s" % (r.get("parent"), "; ".join(src) or "no ruling or choice",
                                             ("; files: " + "; ".join(p(f) for f in files)) if files else ""),
         "- **Judged or settled by:** rules %s (coverage %s); decisions %s" % (
             ", ".join(sb.get("rules") or []) or "none", r.get("rule_coverage"), ", ".join(map(str, sb.get("decisions") or [])) or "none"),
         "- **TEST-PLAN:** " + ("; ".join(tp.get(rid, [])) or "not named by id"),
         "- **Current reading:** " + reading + (" (%d evidence entries; `REQUIREMENTS-TRACE.md` lists them)" % len(r.get("evidence") or []) if r.get("evidence") else ""),
         "- **Waits on:** " + (", ".join(waits) or "nothing")]
    if r.get("resolved_by"): L.append("- **Resolved by:** " + p(r["resolved_by"]))
    if r.get("tbd_effect"): L.append("- **TBD effect:** " + p(r["tbd_effect"]))
    for row in pend.get(rid, []):
        st = row_state(row, dec, data)
        L.append("- **Pending owner decision %s:** %s; the restatement it applies is prepared, not applied." % (row, st))
    if rid in changed: L.append("- **Changed since H3:** %s (section 6)." % ", ".join(changed[rid]))
    L.append("")
    return L


def change_record(req, h3, data, changes):
    L = ["## 6. Change record since H3", "",
         p("Computed from H3's registry as released (`%s`, member sha256/16 `%s`, %s) against this registry. A change to a "
           "statement, acceptance, applicability, allocation, verification, release effect, kind, parent or status is a "
           "change to the baseline and is listed with its downstream impact; readings, bindings and open items move "
           "without a review of the baseline and are counted." % (h3["source"], h3["member_sha256"][:16], h3["baseline_state"])), "",
         "### 6.1 Baseline changes", "", "| Record | Change | Fields | Why | Layers affected |", "|---|---|---|---|---|"]
    imp = data.get("impacts") or {}
    for rid, kind, f in changes:
        lay = ", ".join(str(k) for k, v in sorted((imp[rid].get("layers") or {}).items(), key=lambda x: str(x[0])) if p(v) != "none")
        L.append("| %s | %s | %s | %s | %s |" % (rid, kind, ", ".join(f), cell(imp[rid]["why"]), lay or "none"))
    if not changes: L.append("| none | | | | |")
    cur = {r["id"]: r for r in req["records"]}
    rd = [(i, h3["records"][i].get("evidence_result"), r.get("evidence_result")) for i, r in cur.items()
          if i in h3["records"] and h3["records"][i].get("evidence_result") != r.get("evidence_result")]
    nev = sum(1 for i, r in cur.items() if len(r.get("evidence") or []) != h3["evidence_counts"].get(i, 0))
    add = lambda k: sorted(set(x["id"] for x in req[k]) - set(h3[k]), key=lambda s: (len(s), s))
    gone = lambda k: sorted(set(h3[k]) - set(x["id"] for x in req[k]), key=lambda s: (len(s), s))
    L += ["", "### 6.2 Rulings, choices, items and readings", "",
          "- **Owner rulings added:** " + (", ".join("%s (%s, %s)" % (x["id"], x["ruled_on"], p(x["title"])) for x in req["owner_rulings"] if x["id"] in add("owner_rulings")) or "none"),
          "- **Session choices added:** " + (", ".join(add("session_choices")) or "none"),
          "- **Open items added:** " + (", ".join(add("open_items")) or "none"),
          "- **Open items closed:** " + (", ".join(add("closed_items")) or "none"),
          "- **Readings that changed result:** " + (", ".join("%s %s to %s" % x for x in sorted(rd)) or "none"),
          "- **Records whose evidence list changed:** %d" % nev,
          "- **The needs document's pin:** %s" % ("unchanged" if h3["needs_document_sha256"] == req["needs_document_sha256"] else
                                                   "re-taken, `%s` to `%s` (CONOPS re-stamped and restored; its needs table unchanged, which the validator checks)"
                                                   % (h3["needs_document_sha256"][:16], req["needs_document_sha256"][:16])),
          ""]
    return L


def render_all(root=ROOT, registry=None):
    data = load_data()
    req = R.load_requirements(registry)
    data["_registry_sha16"] = sha16_bytes(open(registry or R.REQUIREMENTS, "rb").read())
    errs, _w = R.validate_requirements(req, root=root, citing=())
    if errs: raise RenderError("the registry does not validate (%d errors): %s" % (len(errs), "; ".join(errs[:3])))
    h3 = load_h3()
    dec = decided(req, data)
    out = {PAGES["decisions"]: page_decisions(req, data, dec),
           PAGES["recon"]: page_recon(req, data, dec, h3, root),
           PAGES["spec"]: page_spec(req, data, dec, h3, root)}
    for name, body in out.items():
        for d in DASHES:
            if d in body: raise RenderError("%s would carry a dash character" % name)
        check_links(name, body)
    return out


def main(argv):
    if "--freeze" in argv:
        body = freeze(load_data())
        open(DIGEST, "w", encoding="utf-8").write(body)
        print("render_l3r2: wrote %s" % rel(DIGEST)); return 0
    reg = argv[argv.index("--registry") + 1] if "--registry" in argv else None
    out = argv[argv.index("--out-dir") + 1] if "--out-dir" in argv else HERE
    try: pages = render_all(registry=reg)
    except RenderError as e:
        print("render_l3r2: REFUSED: %s" % e); return 1
    if "--check" in argv:
        bad = [n for n, b in pages.items() if not os.path.exists(os.path.join(out, n)) or open(os.path.join(out, n), encoding="utf-8").read() != b]
        for n in bad: print("render_l3r2: %s differs from what the inputs render" % n)
        print("render_l3r2: %d page(s), %d out of date" % (len(pages), len(bad)))
        return 1 if bad else 0
    for n, b in pages.items():
        open(os.path.join(out, n), "w", encoding="utf-8").write(b)
        print("render_l3r2: wrote %s (%d lines)" % (n, b.count("\n")))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))

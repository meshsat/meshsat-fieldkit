def t_a_comparator_without_the_page_frame_date_is_caught_by_these_fixtures():
    """The round-1 defect as a negative control: with N2 switched off, the acceptable all-dates fixture reads
    DIFFERENT, which is the failure the round-1 challenger found."""
    d = _dir(); a = _put(d, "a.kicad_sch", _sch()); b = _put(d, "b.kicad_sch", _sch(date="2027-01-02"))
    saved = RC._N2; RC._N2 = re.compile(r"(?!x)x(x)(x)(x)")   # never matches, three groups like N2
    try: r = RC.cmp_sch(a, b)
    finally: RC._N2 = saved
    assert r["result"] == "DIFFERENT", "a comparator without N2 passed a date-only change: the fixture does not bite"



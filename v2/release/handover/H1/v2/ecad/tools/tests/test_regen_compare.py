def t_a_reference_on_one_side_only_is_a_parity_difference():
    """DEFECTIVE: board E's D9 and D10 are in the netlist and not on the committed E17 board. The draft of 25
    September read that DIFFERENT; the first committed copy counted values and lands alone and read PARITY.
    ACCEPTABLE: a board-only mounting hole or test point is netlist_board's declared exception, not a difference."""
    import test_netlist_parts as NPT
    d = _dir()
    net = NPT.D12_NET + [("D9", "SMCJ40A", "Diode_SMD:D_SMC"), ("D10", "USBLC6-2SC6", "Package_TO_SOT_SMD:SOT-23-6")]
    same = [(x, v, f.split(":")[-1]) for x, v, f in NPT.D12_NET]

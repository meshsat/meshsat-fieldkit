def _sch(date="2026-09-20", label="X7", value="10k", lib_body='(pin passive line (at 0 3.81 270) (length 1.27))',
         wire_x="50.80"):
    frame = lambda k: ('\t(text "page %d of 2   MeshSat field kit V2, CERN-OHL-S-2.0   PROTOTYPE, nothing built   %s" '
                       '(exclude_from_sim no) (at 400 290 0) (effects (font (size 1.27 1.27))) (uuid "f%d"))\n' % (k, date, k))
    head = lambda k: '\t(text "PCB-X TEST BOARD   %s" (exclude_from_sim no) (at 10 10 0) (uuid "h%d"))\n' % (label, k)
    return ('(kicad_sch (version 20250114) (generator "eeschema")\n'
            '\t(paper "User" 838.2 297.18)\n'
            '\t(title_block (title "MeshSat Field Kit carrier - PCB-X TEST") (date "%s") (rev "A") (company "MeshSat") '
            '(comment 1 "Phase %s schematic, generated by tools/gen_sch_x.py"))\n'
            '\t(lib_symbols\n\t\t(symbol "Device:R" (in_bom yes) (on_board yes)\n\t\t\t%s\n\t\t)\n\t)\n'
            '\t(symbol (lib_id "Device:R") (at 50.8 35.56 0) (unit 1) (in_bom yes) (on_board yes) (uuid "u1")\n'
            '\t\t(property "Reference" "R1" (at 0 0 0))\n\t\t(property "Value" "%s" (at 0 0 0))\n'
            '\t\t(property "Footprint" "Resistor_SMD:R_0603_1608Metric" (at 0 0 0))\n\t)\n'
            '\t(wire (pts (xy %s 30.48) (xy 60.96 30.48)) (stroke (width 0) (type default)) (uuid "w1"))\n'
            % (date, label, lib_body, value, wire_x)) + frame(1) + frame(2) + head(1) + head(2) + ")\n"


def _net(date="2026-09-20T12:00:00+0000", tdate="2026-09-20", label="X7", pin="1", tool="Eeschema 9.0.9", order=("R1", "R2"),
         tstamp="t1"):
    comp = {"R1": '    (comp (ref "R1")\n      (value "10k")\n      (footprint "Resistor_SMD:R_0603_1608Metric")\n'
                  '      (libsource (lib "Device") (part "R") (description "Resistor"))\n      (tstamps "%s"))\n' % tstamp,
            "R2": '    (comp (ref "R2")\n      (value "1k")\n      (footprint "Resistor_SMD:R_0603_1608Metric")\n'
                  '      (libsource (lib "Device") (part "R") (description "Resistor"))\n      (tstamps "t2"))\n'}
    return ('(export (version "E")\n  (design\n    (source "/root/x/pcb-x.kicad_sch")\n    (date "%s")\n    (tool "%s")\n'
            '    (sheet (number "1") (name "/") (tstamps "/")\n      (title_block\n        (title "MeshSat Field Kit carrier - PCB-X TEST")\n'
            '        (company "MeshSat")\n        (rev "A")\n        (date "%s")\n        (source "pcb-x.kicad_sch")\n'
            '        (comment (number "1") (value "Phase %s schematic")))))\n  (components\n%s  )\n  (nets\n'
            '    (net (code "1") (name "/SIG")\n      (node (ref "R1") (pin "%s") (pintype "passive"))\n'
            '      (node (ref "R2") (pin "1") (pintype "passive")))\n  )\n)\n'
            % (date, tool, tdate, label, "".join(comp[r] for r in order), pin))


def _put(d, name, text):
    p = os.path.join(d, name); open(p, "w").write(text); return p


def _dir():
    return tempfile.mkdtemp(prefix="rc-")


# ---------------------------------------------------------------- schematic
def t_every_date_the_generator_writes_is_noise_and_nothing_else_is():
    d = _dir(); a = _put(d, "a.kicad_sch", _sch())
    r = RC.cmp_sch(a, a); assert r["result"] == "PARITY", r
    r = RC.cmp_sch(a, _put(d, "b.kicad_sch", _sch(date="2027-01-02")))           # ACCEPTABLE: title and both frames
    assert r["result"] == "PARITY_AFTER_NOISE", r
    assert r["noise_removed"][1]["N1_title_date"] == 1 and r["noise_removed"][1]["N2_page_frame_date"] == 2, r["noise_removed"]
    r = RC.cmp_sch(a, _put(d, "c.kicad_sch", _sch(date="2027-01-02", label="ZZ9")))
    assert r["result"] == "PARITY_AFTER_NOISE" and r.get("labels_differ") and r["phase_labels"] == [["X7"], ["ZZ9"]], r



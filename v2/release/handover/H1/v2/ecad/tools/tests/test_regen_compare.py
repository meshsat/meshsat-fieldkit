#!/usr/bin/env python3
"""The regeneration parity comparator: what is noise, and that nothing else is (MESHSAT-1357, 26 September 2026).

`regen_compare.py` is the instrument behind the owner's condition 5 ("generator is current" needs parity). W7 ran
it on the KiCad box on 25 September (box 52646493, commit 82dd1e4d) and validated it against the six real boards
with positive and negative controls (its validate.json, sha16 afa316ed906e6630): an all-dates copy of every
schematic read PARITY_AFTER_NOISE, and a date or a value inside a placed part, a lib_symbols body or a wire read
DIFFERENT with the right bucket. The committed copy reproduces that draft's output on all 48 of those real-file
comparisons (checked on 26 September against the draft, sha16 8099a3df2ba7b5c2). These fixtures carry the same
controls on small synthetic files, so they run anywhere and cannot drift with the boards.

The round-1 comparator had no N2 (the page-frame date); the round-1 challenger showed a date-only change then read
DIFFERENT. `t_a_comparator_without_the_page_frame_date_is_caught_by_these_fixtures` keeps that defect findable.
"""

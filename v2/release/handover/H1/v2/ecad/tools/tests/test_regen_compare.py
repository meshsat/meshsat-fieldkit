def t_the_box_run_reads_the_board_directories_from_the_clone_and_judges_every_artefact():
    """End to end on a throwaway clone: the committed files come from HEAD, the regenerated ones differ only by
    noise, and every row reads PARITY or PARITY_AFTER_NOISE; a board whose regeneration is absent reads
    MISSING_INPUT, which is not a pass."""
    if not shutil.which("git"): raise Skip("no git here")
    repo = _dir(); ecad = os.path.join(repo, "v2", "ecad"); tools = os.path.join(ecad, "tools")
    os.makedirs(os.path.join(tools, "routeflow")); os.makedirs(os.path.join(ecad, "pcb-x-x7", "out"))
    json.dump({"board": "pcb-x", "project": "v2/ecad/pcb-x-x7"}, open(os.path.join(tools, "routeflow", "x.json"), "w"))
    json.dump({"board": "pcb-y", "project": "v2/ecad/pcb-y"}, open(os.path.join(tools, "routeflow", "y.json"), "w"))
    open(os.path.join(tools, "gen_sch_x.py"), "w").write("# generator\n")      # y has none, so it is not a board here
    import test_netlist_parts as NPT
    parts = [("R1", "10k", "Resistor_SMD:R_0603_1608Metric"), ("R2", "1k", "Resistor_SMD:R_0603_1608Metric")]
    base = os.path.join(ecad, "pcb-x-x7")
    _put(base, "pcb-x.kicad_sch", _sch()); _put(base, "pcb-x.kicad_pcb", NPT._board([(r, v, f.split(":")[-1]) for r, v, f in parts]))
    _put(os.path.join(base, "out"), "pcb-x.net", _net())
    _put(os.path.join(base, "out"), "pcb-x-intent.json", '{"written": "1", "rails": 2}')
    _put(os.path.join(base, "out"), "pcb-x.net.prov.json", '{"generator_sha": "g", "taken": "1"}')
    g = ["git", "-C", repo, "-c", "user.name=fixture", "-c", "user.email=fixture@example.invalid"]
    subprocess.run(g + ["init", "-q"], check=True); subprocess.run(g + ["add", "-A"], check=True)
    subprocess.run(g + ["commit", "-q", "-m", "fixture"], check=True)
    assert RC.boards_of(repo) == {"x": ("pcb-x-x7", "pcb-x")}, RC.boards_of(repo)
    out = _dir(); o = os.path.join(out, "x")
    for sub in ("ref", "regen"): os.makedirs(os.path.join(o, sub))
    _put(os.path.join(o, "ref"), "pcb-x.net", _net(date="2027-01-02T00:00:00+0000"))
    _put(os.path.join(o, "ref"), "pcb-x-bom.csv", "Reference,Value\nR1,10k\nR2,1k\n")
    _put(os.path.join(o, "ref"), "pcb-x-erc.json", '{"sheets": []}')
    _put(os.path.join(o, "regen"), "pcb-x.kicad_sch", _sch(date="2027-01-02"))
    _put(os.path.join(o, "regen"), "pcb-x.net", _net(date="2027-01-02T00:00:00+0000", tdate="2027-01-02"))
    _put(os.path.join(o, "regen"), "pcb-x-intent.json", '{"written": "2", "rails": 2}')
    _put(os.path.join(o, "regen"), "pcb-x.net.prov.json", '{"generator_sha": "g", "taken": "2"}')
    _put(os.path.join(o, "regen"), "pcb-x-bom.csv", "Reference,Value\nR2,1k\nR1,10k\n")
    _put(os.path.join(o, "regen"), "pcb-x-erc.json", '{"sheets": []}')
    res = RC.box(repo, out)
    bad = {k: v["result"] for k, v in res["x"].items() if not str(v["result"]).startswith("PARITY")}
    assert not bad, bad
    # a netlist_board verdict beside the run is reported and does not decide the exit code: it reads PASS, never
    # PARITY, and counting it made every clean run exit 1 (the draft's behaviour, carried into the first copy)
    os.makedirs(os.path.join(o, "v-committed"))
    json.dump({"tool": "netlist_board", "verdict": "PASS", "counts": {}}, open(os.path.join(o, "v-committed", "netlist_board.verdict.json"), "w"))
    rc = RC.main(["box", repo, out])
    assert rc == 0, "a clean run with a netlist_board PASS beside it exited %s" % rc
    assert json.load(open(os.path.join(out, "parity.json")))["x"]["sch002_v-committed"]["result"] == "PASS"
    os.remove(os.path.join(o, "regen", "pcb-x-bom.csv"))
    res = RC.box(repo, out)
    assert res["x"]["bom_export_committed_vs_regen"]["result"] == "MISSING_INPUT", res["x"]["bom_export_committed_vs_regen"]
